Truncate :
	Truncate use to delete a data from table.
	But the key difference is truncate reset all the keys present in the table.

	-- Syntax :
		truncate table tbl_name

	-- Example :
		Select * from tbl_StudentDetail

		Delete from tbl_StudentDetail

		Insert into tbl_StudentDetail(Student_Id,Student_Subject,Student_Marks)
		values(2,'Maths',59)

		Truncate table tbl_StudentDetail